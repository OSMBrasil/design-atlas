#!/usr/bin/env node
/**
 * Builds @design-atlas/ms-icons completely offline from svg/synced/ and svg/manual/.
 * Generates:
 *   - dist/index.js (ESM, tree-shakeable named exports + icons map + renderIcon helper)
 *   - dist/index.cjs (CJS)
 *   - dist/index.d.ts (TypeScript declarations)
 *   - dist/svg/*.svg (individual normalized SVGs)
 *   - dist/sprite.svg (SVG sprite with stable IDs: atl-icon-<name>)
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalizeSvg } from './sync.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(__dirname, '..');
const configPath = join(pkgRoot, 'icons.config.json');
const syncedDir = join(pkgRoot, 'svg', 'synced');
const manualDir = join(pkgRoot, 'svg', 'manual');
const distDir = join(pkgRoot, 'dist');
const distSvgDir = join(distDir, 'svg');

function toCamelCase(name) {
  return name.replace(/[-_]([a-z0-9])/gi, (_, ch) => ch.toUpperCase());
}

function parseNormalizedSvg(svgText) {
  const vbMatch = svgText.match(/viewBox="([^"]+)"/i);
  const bodyMatch = svgText.match(/<svg[^>]*>([\s\S]*?)<\/svg>/i);
  if (!vbMatch || !bodyMatch) {
    throw new Error('Failed to parse normalized SVG');
  }
  return {
    viewBox: vbMatch[1].trim(),
    body: bodyMatch[1].trim(),
  };
}

function main() {
  const config = JSON.parse(readFileSync(configPath, 'utf8'));
  const rtlMap = new Map(config.icons.map((i) => [i.name, Boolean(i.rtlMirror)]));

  mkdirSync(distSvgDir, { recursive: true });

  const entries = [];

  // 1. Collect synced SVGs
  if (existsSync(syncedDir)) {
    for (const file of readdirSync(syncedDir).filter((f) => f.endsWith('.svg')).sort()) {
      const id = basename(file, '.svg');
      const baseName = id.replace(/-fill$/, '');
      const normalized = normalizeSvg(readFileSync(join(syncedDir, file), 'utf8'));
      const { viewBox, body } = parseNormalizedSvg(normalized);
      entries.push({
        id,
        exportName: toCamelCase(id),
        viewBox,
        body,
        rtlMirror: rtlMap.get(baseName) || false,
        svg: normalized,
      });
    }
  }

  // 2. Collect manual SVGs (normalized with the same pipeline)
  if (existsSync(manualDir)) {
    for (const file of readdirSync(manualDir).filter((f) => f.endsWith('.svg')).sort()) {
      const id = basename(file, '.svg');
      const baseName = id.replace(/-fill$/, '');
      const normalized = normalizeSvg(readFileSync(join(manualDir, file), 'utf8'));
      const { viewBox, body } = parseNormalizedSvg(normalized);
      entries.push({
        id,
        exportName: toCamelCase(id),
        viewBox,
        body,
        rtlMirror: rtlMap.get(baseName) || false,
        svg: normalized,
      });
    }
  }

  // Write individual SVGs
  for (const item of entries) {
    writeFileSync(join(distSvgDir, `${item.id}.svg`), item.svg);
  }

  // Write sprite.svg
  const symbols = entries
    .map(
      (item) =>
        `  <symbol id="atl-icon-${item.id}" viewBox="${item.viewBox}">${item.body}</symbol>`
    )
    .join('\n');
  const sprite =
    `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${symbols}\n</svg>\n`;
  writeFileSync(join(distDir, 'sprite.svg'), sprite);

  // Shared renderIcon implementation
  const renderIconFn = `function escapeAttr(str) {
  return String(str).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

export function renderIcon(icon, options = {}) {
  const { size = '1.5rem', label, className } = options;
  const attrs = [
    'xmlns="http://www.w3.org/2000/svg"',
    \`viewBox="\${icon.viewBox}"\`,
    \`width="\${escapeAttr(size)}"\`,
    \`height="\${escapeAttr(size)}"\`,
    'fill="currentColor"',
  ];
  if (className) attrs.push(\`class="\${escapeAttr(className)}"\`);
  if (icon.rtlMirror) attrs.push('data-rtl-mirror="true"');
  if (label) {
    attrs.push('role="img"', \`aria-label="\${escapeAttr(label)}"\`);
  } else {
    attrs.push('aria-hidden="true"', 'focusable="false"');
  }
  return \`<svg \${attrs.join(' ')}>\${icon.body}</svg>\`;
}`;

  // Write ESM (dist/index.js)
  const esmLines = [
    '// Auto-generated by scripts/build.mjs — do not edit manually.',
    ...entries.map(
      (item) =>
        `export const ${item.exportName} = Object.freeze(${JSON.stringify({
          name: item.id,
          viewBox: item.viewBox,
          body: item.body,
          rtlMirror: item.rtlMirror,
        })});`
    ),
    '',
    `export const icons = Object.freeze({`,
    ...entries.map((item) => `  '${item.id}': ${item.exportName},`),
    `});`,
    '',
    renderIconFn,
    '',
  ];
  writeFileSync(join(distDir, 'index.js'), esmLines.join('\n'));

  // Write CJS (dist/index.cjs)
  const cjsRender = renderIconFn.replace('export function renderIcon', 'function renderIcon');
  const cjsLines = [
    "'use strict';",
    '// Auto-generated by scripts/build.mjs — do not edit manually.',
    ...entries.map(
      (item) =>
        `const ${item.exportName} = Object.freeze(${JSON.stringify({
          name: item.id,
          viewBox: item.viewBox,
          body: item.body,
          rtlMirror: item.rtlMirror,
        })});`
    ),
    '',
    `const icons = Object.freeze({`,
    ...entries.map((item) => `  '${item.id}': ${item.exportName},`),
    `});`,
    '',
    cjsRender,
    '',
    `module.exports = {`,
    ...entries.map((item) => `  ${item.exportName},`),
    `  icons,`,
    `  renderIcon,`,
    `};`,
    '',
  ];
  writeFileSync(join(distDir, 'index.cjs'), cjsLines.join('\n'));

  // Write TypeScript declarations (dist/index.d.ts)
  const dtsLines = [
    '// Auto-generated by scripts/build.mjs — do not edit manually.',
    'export interface IconDefinition {',
    '  readonly name: string;',
    '  readonly viewBox: string;',
    '  readonly body: string;',
    '  readonly rtlMirror: boolean;',
    '}',
    '',
    'export interface RenderIconOptions {',
    '  size?: string;',
    '  label?: string;',
    '  className?: string;',
    '}',
    '',
    ...entries.map((item) => `export declare const ${item.exportName}: IconDefinition;`),
    '',
    'export declare const icons: Readonly<Record<string, IconDefinition>>;',
    'export declare function renderIcon(icon: IconDefinition, options?: RenderIconOptions): string;',
    '',
  ];
  writeFileSync(join(distDir, 'index.d.ts'), dtsLines.join('\n'));

  console.log(`✅ Built @design-atlas/ms-icons (${entries.length} icons, ESM/CJS/DTS, sprite.svg).`);
}

main();
