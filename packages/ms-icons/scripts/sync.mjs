#!/usr/bin/env node
/**
 * Synchronizes Material Symbols SVGs from @material-symbols/svg-400 into svg/synced/.
 * Usage:
 *   node scripts/sync.mjs         (writes normalized SVGs)
 *   node scripts/sync.mjs --check (verifies svg/synced/ matches expected output; exits 1 on drift)
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(__dirname, '..');
const configPath = join(pkgRoot, 'icons.config.json');
const syncedDir = join(pkgRoot, 'svg', 'synced');
const isCheck = process.argv.includes('--check');

export function normalizeSvg(rawSvg) {
  const viewBoxMatch = rawSvg.match(/viewBox="([^"]+)"/i);
  if (!viewBoxMatch) {
    throw new Error('SVG is missing a viewBox attribute');
  }
  const viewBox = viewBoxMatch[1].trim();

  // Extract inner content between <svg ...> and </svg>
  const innerMatch = rawSvg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/i);
  if (!innerMatch) {
    throw new Error('Invalid SVG structure');
  }

  let body = innerMatch[1]
    // Remove <mask>...</mask>, <defs>...</defs>, <style>...</style>, comments
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<mask[\s\S]*?<\/mask>/gi, '')
    .replace(/<style[\s\S]*?<\/style>/gi, '')
    // Remove id, mask, style, class, width, height attributes
    .replace(/\s+(?:id|mask|style|class|width|height)="[^"]*"/gi, '')
    // Normalize explicit fill/stroke colors (other than none) to currentColor
    .replace(/\sfill="(?!none")[^"]*"/gi, ' fill="currentColor"')
    .replace(/\sstroke="(?!none")[^"]*"/gi, ' stroke="currentColor"')
    .replace(/\s+/g, ' ')
    .trim();

  // Unwrap empty <g> wrappers left after stripping mask attributes
  body = body.replace(/<g>\s*([\s\S]*?)\s*<\/g>/gi, '$1').trim();

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="currentColor">${body}</svg>\n`;
}

function resolveSourceDir(sourcePkg, style) {
  const candidates = [
    join(pkgRoot, 'node_modules', sourcePkg, style),
    join(pkgRoot, '..', '..', 'node_modules', sourcePkg, style),
  ];
  for (const dir of candidates) {
    if (existsSync(dir)) return dir;
  }
  throw new Error(
    `Could not locate "${sourcePkg}/${style}" in node_modules. Run "pnpm install" first.`
  );
}

function main() {
  const config = JSON.parse(readFileSync(configPath, 'utf8'));
  const sourceDir = resolveSourceDir(config.source, config.style);

  // 1. Validate all configured icons exist BEFORE writing anything
  const planned = new Map();
  const missing = [];

  for (const entry of config.icons) {
    const fills = Array.isArray(entry.fills) && entry.fills.length > 0 ? entry.fills : [0];
    for (const fill of fills) {
      const fileName = fill === 1 ? `${entry.name}-fill.svg` : `${entry.name}.svg`;
      const srcPath = join(sourceDir, fileName);
      if (!existsSync(srcPath)) {
        missing.push(`${entry.name} (fill=${fill}, expected ${fileName})`);
      } else {
        const raw = readFileSync(srcPath, 'utf8');
        planned.set(fileName, normalizeSvg(raw));
      }
    }
  }

  if (missing.length > 0) {
    console.error(`❌ Missing ${missing.length} icon(s) in ${config.source}/${config.style}:`);
    for (const item of missing) console.error(`   - ${item}`);
    process.exit(1);
  }

  const readmeContent =
    '# Generated Directory — Do Not Edit Manually\n\n' +
    'All SVG files in this directory are generated by `pnpm icons:sync` from `icons.config.json`.\n' +
    'Any manual edit will cause `pnpm icons:check` to fail.\n';

  if (isCheck) {
    if (!existsSync(syncedDir)) {
      console.error('❌ svg/synced/ directory does not exist. Run "pnpm icons:sync".');
      process.exit(1);
    }

    const existingFiles = readdirSync(syncedDir).filter((f) => f.endsWith('.svg'));
    const diffs = [];

    for (const [fileName, expected] of planned.entries()) {
      const target = join(syncedDir, fileName);
      if (!existsSync(target)) {
        diffs.push(`Missing synced file: ${fileName}`);
      } else {
        const actual = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
        if (actual !== expected) {
          diffs.push(`Modified synced file (manual edit detected): ${fileName}`);
        }
      }
    }

    for (const fileName of existingFiles) {
      if (!planned.has(fileName)) {
        diffs.push(`Extra unconfigured SVG in svg/synced/: ${fileName}`);
      }
    }

    if (diffs.length > 0) {
      console.error('❌ Icon sync check failed:');
      for (const d of diffs) console.error(`   - ${d}`);
      console.error('Run "pnpm icons:sync" to regenerate svg/synced/.');
      process.exit(1);
    }

    console.log(`✅ Icons sync check passed (${planned.size} SVGs match ${config.source}/${config.style}).`);
    return;
  }

  // Write mode
  mkdirSync(syncedDir, { recursive: true });
  writeFileSync(join(syncedDir, 'README.md'), readmeContent);

  // Remove stale SVGs not in config
  for (const existing of readdirSync(syncedDir).filter((f) => f.endsWith('.svg'))) {
    if (!planned.has(existing)) {
      unlinkSync(join(syncedDir, existing));
    }
  }

  for (const [fileName, content] of planned.entries()) {
    writeFileSync(join(syncedDir, fileName), content);
  }

  console.log(`✅ Synced ${planned.size} SVGs from ${config.source}/${config.style} into svg/synced/.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
